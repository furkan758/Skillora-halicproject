/* Skillora | Microsoft SQL Server 2016 SP1+ | Fresh database only.
   Use 05_upgrade_legacy.sql instead if the original three scripts were installed.
   This package contains SQL only. No FastAPI service is implemented. */
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET ARITHABORT ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET NUMERIC_ROUNDABORT OFF;

IF @@TRANCOUNT <> 0
    THROW 51000, 'Run setup without an open transaction.', 1;
IF OBJECT_ID(N'dbo.FOLDERS', N'U') IS NOT NULL
    OR OBJECT_ID(N'dbo.SKILLS', N'U') IS NOT NULL
    OR OBJECT_ID(N'dbo.EMPLOYEES', N'U') IS NOT NULL
    OR OBJECT_ID(N'dbo.SCENARIOS', N'U') IS NOT NULL
    THROW 51001, 'Existing tables detected. Use the legacy upgrade script.', 1;

BEGIN TRY
    BEGIN TRANSACTION;

    CREATE TABLE dbo.DEPARTMENTS (
        DepartmentID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_DEPARTMENTS PRIMARY KEY,
        DepartmentName NVARCHAR(100) NOT NULL,
        NameKey AS (LOWER(LTRIM(RTRIM(DepartmentName))) COLLATE Latin1_General_100_CI_AS_SC) PERSISTED,
        CONSTRAINT CK_DEPARTMENTS_Name CHECK (LEN(LTRIM(RTRIM(DepartmentName))) > 0)
    );
    CREATE UNIQUE INDEX UX_DEPARTMENTS_NameKey ON dbo.DEPARTMENTS(NameKey);

    CREATE TABLE dbo.FOLDERS (
        FolderID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_FOLDERS PRIMARY KEY,
        FolderName NVARCHAR(100) NOT NULL,
        Description NVARCHAR(500) NULL,
        IsDefault BIT NOT NULL CONSTRAINT DF_FOLDERS_IsDefault DEFAULT (0),
        IsActive BIT NOT NULL CONSTRAINT DF_FOLDERS_IsActive DEFAULT (1),
        CreatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_FOLDERS_CreatedAt DEFAULT (SYSUTCDATETIME()),
        NameKey AS (LOWER(LTRIM(RTRIM(FolderName))) COLLATE Latin1_General_100_CI_AS_SC) PERSISTED,
        CONSTRAINT CK_FOLDERS_Name CHECK (LEN(LTRIM(RTRIM(FolderName))) > 0),
        CONSTRAINT CK_FOLDERS_Default CHECK (IsDefault = 0 OR (FolderName = N'Unsorted' AND IsActive = 1))
    );
    CREATE UNIQUE INDEX UX_FOLDERS_NameKey ON dbo.FOLDERS(NameKey);
    CREATE UNIQUE INDEX UX_FOLDERS_OneDefault ON dbo.FOLDERS(IsDefault) WHERE IsDefault = 1;

    -- Required structural records exist even when the optional demo catalog is skipped.
    INSERT dbo.DEPARTMENTS (DepartmentName) VALUES (N'Unassigned');
    SET IDENTITY_INSERT dbo.FOLDERS ON;
    INSERT dbo.FOLDERS (FolderID, FolderName, IsDefault) VALUES (16, N'Unsorted', 1);
    SET IDENTITY_INSERT dbo.FOLDERS OFF;

    CREATE TABLE dbo.SKILLS (
        SkillID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_SKILLS PRIMARY KEY,
        FolderID INT NOT NULL,
        SkillName NVARCHAR(100) NOT NULL,
        Description NVARCHAR(500) NULL,
        IsActive BIT NOT NULL CONSTRAINT DF_SKILLS_IsActive DEFAULT (1),
        CreatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_SKILLS_CreatedAt DEFAULT (SYSUTCDATETIME()),
        NameKey AS (LOWER(LTRIM(RTRIM(SkillName))) COLLATE Latin1_General_100_CI_AS_SC) PERSISTED,
        CONSTRAINT FK_SKILLS_FOLDERS FOREIGN KEY (FolderID) REFERENCES dbo.FOLDERS(FolderID),
        CONSTRAINT CK_SKILLS_Name CHECK (LEN(LTRIM(RTRIM(SkillName))) > 0)
    );
    CREATE UNIQUE INDEX UX_SKILLS_NameKey ON dbo.SKILLS(NameKey);
    CREATE INDEX IX_SKILLS_FolderID ON dbo.SKILLS(FolderID);

    CREATE TABLE dbo.EMPLOYEES (
        EmployeeID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_EMPLOYEES PRIMARY KEY,
        FirstName NVARCHAR(100) NOT NULL,
        LastName NVARCHAR(100) NOT NULL,
        Gender NVARCHAR(30) NULL,
        DepartmentID INT NOT NULL,
        JobTitle NVARCHAR(100) NOT NULL CONSTRAINT DF_EMPLOYEES_JobTitle DEFAULT (N'Team member'),
        IsAvailable BIT NOT NULL CONSTRAINT DF_EMPLOYEES_IsAvailable DEFAULT (1),
        IsActive BIT NOT NULL CONSTRAINT DF_EMPLOYEES_IsActive DEFAULT (1),
        CONSTRAINT FK_EMPLOYEES_DEPARTMENTS FOREIGN KEY (DepartmentID) REFERENCES dbo.DEPARTMENTS(DepartmentID),
        CONSTRAINT CK_EMPLOYEES_FirstName CHECK (LEN(LTRIM(RTRIM(FirstName))) > 0),
        CONSTRAINT CK_EMPLOYEES_LastName CHECK (LEN(LTRIM(RTRIM(LastName))) > 0),
        CONSTRAINT CK_EMPLOYEES_Gender CHECK (Gender IS NULL OR Gender IN (N'Male', N'Female', N'Not specified', N'Prefer not to say'))
    );
    CREATE INDEX IX_EMPLOYEES_DepartmentID ON dbo.EMPLOYEES(DepartmentID);

    CREATE TABLE dbo.EMPLOYEE_SKILLS (
        EmployeeSkillID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_EMPLOYEE_SKILLS PRIMARY KEY,
        EmployeeID INT NOT NULL,
        SkillID INT NOT NULL,
        ExperienceYears DECIMAL(4,1) NULL,
        -- NULL explicitly means unassessed, and is excluded from candidate ranking.
        ProficiencyLevel TINYINT NULL,
        IsActive BIT NOT NULL CONSTRAINT DF_EMPLOYEE_SKILLS_IsActive DEFAULT (1),
        CONSTRAINT FK_EMPLOYEE_SKILLS_EMPLOYEES FOREIGN KEY (EmployeeID) REFERENCES dbo.EMPLOYEES(EmployeeID),
        CONSTRAINT FK_EMPLOYEE_SKILLS_SKILLS FOREIGN KEY (SkillID) REFERENCES dbo.SKILLS(SkillID),
        CONSTRAINT UQ_EMPLOYEE_SKILLS_EmployeeSkill UNIQUE (EmployeeID, SkillID),
        CONSTRAINT CK_EMPLOYEE_SKILLS_ExperienceYears CHECK (ExperienceYears IS NULL OR ExperienceYears >= 0),
        CONSTRAINT CK_EMPLOYEE_SKILLS_Proficiency CHECK (ProficiencyLevel IS NULL OR ProficiencyLevel BETWEEN 1 AND 5)
    );
    CREATE INDEX IX_EMPLOYEE_SKILLS_SkillID ON dbo.EMPLOYEE_SKILLS(SkillID);

    CREATE TABLE dbo.SCENARIOS (
        ScenarioID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_SCENARIOS PRIMARY KEY,
        ClientName NVARCHAR(150) NOT NULL,
        BaseTitle NVARCHAR(200) NOT NULL,
        ProjectTitle NVARCHAR(220) NOT NULL,
        TitleSequence INT NOT NULL CONSTRAINT DF_SCENARIOS_TitleSequence DEFAULT (1),
        ProjectBrief NVARCHAR(MAX) NOT NULL CONSTRAINT DF_SCENARIOS_ProjectBrief DEFAULT (N''),
        RequiredPeople INT NOT NULL CONSTRAINT DF_SCENARIOS_RequiredPeople DEFAULT (1),
        OnlyAvailable BIT NOT NULL CONSTRAINT DF_SCENARIOS_OnlyAvailable DEFAULT (0),
        Status NVARCHAR(12) NOT NULL CONSTRAINT DF_SCENARIOS_Status DEFAULT (N'DRAFT'),
        Version INT NOT NULL CONSTRAINT DF_SCENARIOS_Version DEFAULT (1),
        CreatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_SCENARIOS_CreatedAt DEFAULT (SYSUTCDATETIME()),
        UpdatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_SCENARIOS_UpdatedAt DEFAULT (SYSUTCDATETIME()),
        TitleKey AS (LOWER(LTRIM(RTRIM(ProjectTitle))) COLLATE Latin1_General_100_CI_AS_SC) PERSISTED,
        CONSTRAINT CK_SCENARIOS_ClientName CHECK (LEN(LTRIM(RTRIM(ClientName))) > 0),
        CONSTRAINT CK_SCENARIOS_ProjectTitle CHECK (LEN(LTRIM(RTRIM(ProjectTitle))) > 0),
        CONSTRAINT CK_SCENARIOS_BaseTitle CHECK (LEN(LTRIM(RTRIM(BaseTitle))) > 0),
        CONSTRAINT CK_SCENARIOS_RequiredPeople CHECK (RequiredPeople BETWEEN 1 AND 100),
        CONSTRAINT CK_SCENARIOS_TitleSequence CHECK (TitleSequence >= 1),
        CONSTRAINT CK_SCENARIOS_Version CHECK (Version >= 1),
        CONSTRAINT CK_SCENARIOS_Status CHECK (Status IN (N'DRAFT', N'SAVED', N'ARCHIVED'))
    );
    CREATE UNIQUE INDEX UX_SCENARIOS_TitleKey ON dbo.SCENARIOS(TitleKey);

    CREATE TABLE dbo.SCENARIO_REQUIREMENTS (
        ScenarioID INT NOT NULL,
        SkillID INT NOT NULL,
        RequiredCount INT NOT NULL,
        CONSTRAINT PK_SCENARIO_REQUIREMENTS PRIMARY KEY (ScenarioID, SkillID),
        CONSTRAINT FK_SCENARIO_REQUIREMENTS_SCENARIOS FOREIGN KEY (ScenarioID) REFERENCES dbo.SCENARIOS(ScenarioID),
        CONSTRAINT FK_SCENARIO_REQUIREMENTS_SKILLS FOREIGN KEY (SkillID) REFERENCES dbo.SKILLS(SkillID),
        CONSTRAINT CK_SCENARIO_REQUIREMENTS_Count CHECK (RequiredCount BETWEEN 1 AND 100)
    );

    CREATE TABLE dbo.SCENARIO_ASSIGNMENTS (
        ScenarioID INT NOT NULL,
        EmployeeID INT NOT NULL,
        SkillID INT NOT NULL,
        ProficiencyAtSelection TINYINT NOT NULL,
        SelectedAt DATETIME2(0) NOT NULL CONSTRAINT DF_SCENARIO_ASSIGNMENTS_SelectedAt DEFAULT (SYSUTCDATETIME()),
        CONSTRAINT PK_SCENARIO_ASSIGNMENTS PRIMARY KEY (ScenarioID, EmployeeID),
        CONSTRAINT FK_SCENARIO_ASSIGNMENTS_REQUIREMENTS FOREIGN KEY (ScenarioID, SkillID) REFERENCES dbo.SCENARIO_REQUIREMENTS(ScenarioID, SkillID),
        CONSTRAINT FK_SCENARIO_ASSIGNMENTS_EMPLOYEE_SKILLS FOREIGN KEY (EmployeeID, SkillID) REFERENCES dbo.EMPLOYEE_SKILLS(EmployeeID, SkillID),
        CONSTRAINT CK_SCENARIO_ASSIGNMENTS_Proficiency CHECK (ProficiencyAtSelection BETWEEN 1 AND 5)
    );
    CREATE INDEX IX_SCENARIO_ASSIGNMENTS_Requirement ON dbo.SCENARIO_ASSIGNMENTS(ScenarioID, SkillID);
    CREATE INDEX IX_SCENARIO_ASSIGNMENTS_EmployeeSkill ON dbo.SCENARIO_ASSIGNMENTS(EmployeeID, SkillID);

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
PRINT 'Schema created. Run 02_data_seed.sql, 03_views.sql and 04_operations.sql next.';
